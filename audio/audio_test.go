var outFlag = flag.Bool("out", false, "write before/after artifacts to internal/output")

func TestMain(m *testing.M) {
	flag.Parse()
	os.Exit(m.Run())
}

// okPrint prints a success line styled like the failure lines: no
// file:line prefix or indentation, always visible.
func okPrint(format string, args ...any) {
	fmt.Printf("ok: "+format+"\n", args...)
}

// artifactDir walks up from the working directory to the module root
// (the dir containing go.mod) and returns <root>/internal/output.
// go test runs the binary with CWD set to the package dir, so a bare
// relative path would land inside images/ or audio/.
func artifactDir() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(dir + "/go.mod"); err == nil {
			return dir + "/internal/output", nil
		}
		parent := dir[:strings.LastIndexByte(dir, '/')]
		if parent == "" || parent == dir {
			return "", fmt.Errorf("go.mod not found above %s", dir)
		}
		dir = parent
	}
}

// writeArtifact writes an input/gap/output WAV into internal/output
// and prints the path. It is a no-op unless the test runs with -out.
func writeArtifact(t *testing.T, pcm *audio.PCM, name string) {
	t.Helper()
	if !*outFlag {
		return
	}
	outDir, err := artifactDir()
	if err != nil {
		t.Fatalf("locating internal/output: %v", err)
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		t.Fatalf("creating internal/output: %v", err)
	}
	f, err := os.Create(outDir + "/" + name + ".wav")
	if err != nil {
		t.Fatalf("creating artifact: %v", err)
	}
	defer f.Close()
	if err := pcm.WriteWAV(f); err != nil {
		t.Fatalf("writing artifact: %v", err)
	}
	okPrint("wrote internal/output/%s.wav", name)
}

// zeroCrossings counts sign changes between consecutive samples.
func zeroCrossings(xs []int16) int {
	count := 0
	for i := 1; i < len(xs); i++ {
		if (xs[i-1] >= 0 && xs[i] < 0) || (xs[i-1] < 0 && xs[i] >= 0) {
			count++
		}
	}
	return count
}

func TestSineGen(t *testing.T) {
	const (
		rate = 44100
		amp  = int16(20000)
	)

	for _, c := range []struct {
		freq   float64
		durSec float64
	}{
		{440, 0.5},
		{261.626, 1}, // middle C
		{80, 0.2},
	} {
		got := SineGen(rate, c.freq, c.durSec, amp)

		// Frequency check: a sine crosses zero twice per cycle.
		wantX := int(math.Round(2 * c.freq * c.durSec))
		if n := zeroCrossings(got.Samples); math.Abs(float64(n-wantX)) > 1 {
			t.Fatalf("SineGen(%v Hz): %d zero crossings, want ≈ %d", c.freq, n, wantX)
		}

		// Amplitude check: the RMS of a full-scale sine is amp/√2.
		wantRMS := float64(amp) / math.Sqrt2
		if r := got.RMS(); math.Abs(r-wantRMS) > wantRMS*0.05 {
			t.Fatalf("SineGen(%v Hz): RMS %.1f, want ≈ %.1f", c.freq, r, wantRMS)
		}

		// Range check: synthesis must never clip.
		if p := got.Peak(); p > amp {
			t.Fatalf("SineGen(%v Hz): peak %d exceeds amplitude %d", c.freq, p, amp)
		}
		okPrint("SineGen %v Hz × %vs: %d crossings (want ≈ %d), rms %.0f", c.freq, c.durSec, zeroCrossings(got.Samples), wantX, got.RMS())

		if c.freq == 440 {
			// Demonstration artifact: a reference sine generated by the
			// support package, silence, then the exercise output. The
			// two tones must sound identical.
			ref := audio.Sine(rate, c.freq, c.durSec, amp)
			writeArtifact(t, audio.ConcatWithGap(ref, got, 300), "sinegen_before_after")
		}
	}

	// Determinism: same arguments, same samples.
	a := SineGen(rate, 440, 0.1, amp)
	b := SineGen(rate, 440, 0.1, amp)
	for i := range a.Samples {
		if a.Samples[i] != b.Samples[i] {
			t.Fatalf("SineGen not deterministic at sample %d", i)
		}
	}
	okPrint("SineGen deterministic")
}

// sameSamples reports the first index where the two buffers differ,
// or -1.
func firstDiff(a, b *audio.PCM) int {
	if len(a.Samples) != len(b.Samples) {
		return -2
	}
	for i := range a.Samples {
		if a.Samples[i] != b.Samples[i] {
			return i
		}
	}
	return -1
}

func TestNormalize(t *testing.T) {
	const rate = 8000
	src := audio.Sine(rate, 440, 0.25, 20000)

	out := Normalize(src, 12000)
	if out == nil {
		t.Fatal("Normalize returned nil")
	}
	if p := out.Peak(); p != 12000 {
		t.Fatalf("Normalize peak %d, want exactly 12000", p)
	}
	okPrint("Normalize peak 20000→%d exact", out.Peak())

	// Shape preserved: out[i]/target == in[i]/inPeak within rounding.
	factor := 12000.0 / 20000.0
	for i := range out.Samples {
		want := math.Round(float64(src.Samples[i]) * factor)
		if math.Abs(float64(out.Samples[i])-want) > 1 {
			t.Fatalf("Normalize shape differs at sample %d: %d, want ≈ %.0f", i, out.Samples[i], want)
		}
	}
	okPrint("Normalize preserves waveform shape within rounding")

	// Silence: no division by zero, unchanged.
	sil := audio.Silence(rate, 100)
	if got := Normalize(sil, 9000); firstDiff(got, sil) != -1 {
		t.Fatal("Normalize of silence changed the buffer")
	}
	// Boosting is refused.
	if got := Normalize(src, 30000); firstDiff(got, src) != -1 {
		t.Fatal("Normalize must not amplify beyond the current peak")
	}
	okPrint("Normalize silence no-op, boost refused")

	writeArtifact(t, audio.ConcatWithGap(src, out, 300), "normalize_before_after")
}

func TestMixClipped(t *testing.T) {
	const rate = 8000
	a := audio.Sine(rate, 440, 0.1, 20000)
	b := audio.Sine(rate, 880, 0.1, 20000)

	out := MixClipped(a, b)
	if out == nil {
		t.Fatal("MixClipped returned nil")
	}
	if len(out.Samples) != len(a.Samples) {
		t.Fatalf("MixClipped length %d, want %d", len(out.Samples), len(a.Samples))
	}
	// Ceiling clamped where both peak together; linear zone sums.
	clipped, linear := 0, 0
	for i := range out.Samples {
		sum := int32(a.Samples[i]) + int32(b.Samples[i])
		switch {
		case sum > 32767:
			if out.Samples[i] != 32767 {
				t.Fatalf("sum %d not clamped at +ceiling at sample %d", sum, i)
			}
			clipped++
		case sum < -32768:
			if out.Samples[i] != -32768 {
				t.Fatalf("sum %d not clamped at −ceiling at sample %d", sum, i)
			}
			clipped++
		default:
			if out.Samples[i] != int16(sum) {
				t.Fatalf("linear sum wrong at sample %d", i)
			}
			linear++
		}
	}
	okPrint("MixClipped %d linear samples, %d clamped at the ceiling", linear, clipped)

	// Tail pass-through: mixing with silence is the identity.
	sil := audio.Silence(rate, len(a.Samples))
	if got := MixClipped(a, sil); firstDiff(got, a) != -1 {
		t.Fatal("MixClipped with silence must be the identity")
	}
	// Length order: longer buffer keeps its tail.
	short := audio.Silence(rate, 50)
	long := audio.Silence(rate, 100)
	long.Samples[90] = -7
	got := MixClipped(short, long)
	if len(got.Samples) != 100 || got.Samples[90] != -7 {
		t.Fatal("MixClipped tail of the longer buffer lost")
	}
	okPrint("MixClipped silence identity and tail pass-through ok")

	writeArtifact(t, audio.ConcatWithGap(a, out, 300), "mixclipped_before_after")
}

func TestEcho(t *testing.T) {
	const (
		rate    = 8000
		delayMs = 100 // 800 samples, longer than the 0.05s input: no overlap
		decay   = 0.5
		repeats = 2
	)
	src := audio.Sine(rate, 440, 0.05, 16000)
	n := len(src.Samples)

	out := Echo(src, delayMs, decay, repeats)
	if out == nil {
		t.Fatal("Echo returned nil")
	}
	wantLen := n + delayMs*rate/1000*repeats
	if len(out.Samples) != wantLen {
		t.Fatalf("Echo length %d, want %d", len(out.Samples), wantLen)
	}
	okPrint("Echo length %d = input + %d repeats of %d samples", len(out.Samples), repeats, delayMs*rate/1000)

	// Closed form: out[t] = Σ_k decay^k · in[t − k·delay] over
	// repeats landing on t, with 0 for out-of-range reads.
	d := delayMs * rate / 1000
	for i := range out.Samples {
		want := 0.0
		if i < n {
			want += float64(src.Samples[i])
		}
		for k := 1; k <= repeats; k++ {
			j := i - k*d
			if j >= 0 && j < n {
				want += math.Pow(decay, float64(k)) * float64(src.Samples[j])
			}
		}
		w := int16(math.Round(want))
		if w > 32767 {
			w = 32767
		}
		if out.Samples[i] != w {
			t.Fatalf("Echo sample %d = %d, want %d", i, out.Samples[i], w)
		}
	}
	okPrint("Echo matches the closed form decay^k·in(t−k·delay)")

	// Echo of silence is silence; decay 0 is the identity extended.
	sil := audio.Silence(rate, 100)
	if got := Echo(sil, 50, 0.5, 2); got.Peak() != 0 {
		t.Fatal("Echo of silence is not silent")
	}
	// Echo with decay 0 keeps the dry signal unchanged.
	if got := Echo(src, 100, 0, 3); got != nil {
		for i := 0; i < n; i++ {
			if got.Samples[i] != src.Samples[i] {
				t.Fatalf("Echo decay 0: dry sample %d changed", i)
			}
		}
	}
	okPrint("Echo silence in → silence out, decay 0 → dry only")

	writeArtifact(t, audio.ConcatWithGap(src, out, 300), "echo_before_after")
}

func TestMovingAverageLowpass(t *testing.T) {
	const (
		rate = 8000
		k    = 16
	)

	// Identity for k=1.
	src := audio.Sine(rate, 440, 0.1, 12000)
	if got := MovingAverageLowpass(src, 1); firstDiff(got, src) != -1 {
		t.Fatal("k=1 must be the identity")
	}
	okPrint("MovingAverage k=1 is the identity")

	// Probe response on the steady-state region, shifted by the
	// group delay (k-1)/2.
	measure := func(freq float64) float64 {
		in := audio.Sine(rate, freq, 0.2, 12000)
		out := MovingAverageLowpass(in, k)
		// Skip the first seconds: transient + group delay.
		start := rate/4 + k
		var inPeak, outPeak float64
		for i := start; i < len(in.Samples); i++ {
			inPeak = math.Max(inPeak, math.Abs(float64(in.Samples[i])))
			outPeak = math.Max(outPeak, math.Abs(float64(out.Samples[i])))
		}
		return outPeak / inPeak
	}
	slow := measure(50)
	fast := measure(2000)
	dc := measure(0)
	if dc != 1 {
		t.Fatalf("DC gain %.3f, want exactly 1", dc)
	}
	if slow < 0.8 {
		t.Fatalf("50 Hz gain %.3f, want ≥ 0.8 (passband)", slow)
	}
	if fast > 0.35 {
		t.Fatalf("2000 Hz gain %.3f, want ≤ 0.35 (stopband)", fast)
	}
	okPrint("MovingAverage k=%d gains: DC %.2f, 50 Hz %.2f, 2000 Hz %.2f", k, dc, slow, fast)

	// Length preserved.
	out := MovingAverageLowpass(src, k)
	if len(out.Samples) != len(src.Samples) {
		t.Fatalf("length %d, want %d", len(out.Samples), len(src.Samples))
	}

	writeArtifact(t, audio.ConcatWithGap(src, out, 300), "lowpass_before_after")
}

func TestLinearResample(t *testing.T) {
	const rate = 8000

	// Identity at equal rates.
	src := audio.Sine(rate, 440, 0.1, 12000)
	if got := LinearResample(src, rate, rate); firstDiff(got, src) != -1 {
		t.Fatal("1:1 resample must be the identity")
	}
	okPrint("LinearResample 1:1 is the identity")

	// DC stays DC at any rate.
	dc := audio.Silence(rate, 100)
	for i := range dc.Samples {
		dc.Samples[i] = 777
	}
	up := LinearResample(dc, rate, 2*rate)
	for i := range up.Samples {
		if up.Samples[i] != 777 {
			t.Fatalf("DC changed to %d at output sample %d", up.Samples[i], i)
		}
	}
	okPrint("LinearResample DC stays DC at 2× rate")

	// A ramp survives: endpoints aligned, values on the same line.
	ramp := audio.NewPCM(rate)
	for i := range 101 {
		ramp.Samples[i] = int16(10 * i) // 0..1000 over 101 samples
	}
	down := LinearResample(ramp, 100, 50) // 51 samples
	if len(down.Samples) != 51 {
		t.Fatalf("ramp resample length %d, want 51", len(down.Samples))
	}
	for i := range down.Samples {
		p := float64(i) * 2 // source position
		want := int16(math.Round(p * 10))
		if math.Abs(float64(down.Samples[i]-want)) > 1 {
			t.Fatalf("ramp sample %d = %d, want ≈ %d", i, down.Samples[i], want)
		}
	}
	okPrint("LinearResample ramp slope preserved, endpoints aligned")

	// Round trip on a slow sine stays close to the original.
	half := LinearResample(src, rate, rate/2)
	back := LinearResample(half, rate/2, rate)
	err := 0.0
	for i := 0; i < len(back.Samples) && i < len(src.Samples); i++ {
		e := math.Abs(float64(back.Samples[i]) - float64(src.Samples[i]))
		err = math.Max(err, e)
	}
	if err > 200 {
		t.Fatalf("down/up round trip max error %.0f too large", err)
	}
	okPrint("LinearResample down→up round trip max error %.0f (≤ 200)", err)

	writeArtifact(t, audio.ConcatWithGap(src, back, 300), "resample_before_after")
}
